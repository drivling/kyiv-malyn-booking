export function place(list: [string, number][]): Placed[] {
  let b = 0;
  return list.map(([id, beats]) => {
    const shot = SHOTS[id];
    if (!shot) throw new Error(`Немає кадру ${id} у timeline.ts`);
    const from = Math.round(b * BEAT * FPS);
    b += beats;
    const to = Math.round(b * BEAT * FPS);
    return { ...shot, beats, from, dur: to - from };
  });
}

export const totalFrames = (placed: Placed[]) => {
  const last = placed[placed.length - 1];
  return last ? last.from + last.dur : 0;
};
