def _lighter(hex_color, k=0.32):
    """Колір лінії для темної теми — світліший на k до білого."""
    r, g, b = (int(hex_color[i:i + 2], 16) for i in (1, 3, 5))
    return '#%02X%02X%02X' % tuple(round(c + (255 - c) * k) for c in (r, g, b))


