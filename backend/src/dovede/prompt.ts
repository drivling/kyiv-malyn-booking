function placeLine(p: GazetteerPlace): string {
  const note = PLACE_NOTES[p.id];
  const kind = p.isCity ? 'місто' : CITY_LABEL[p.city];
  return `- ${p.id} — ${kind}: ${p.label}${note ? ` (${note})` : ''}`;
}

