def main():
    A = load(path('stops-audit.json'))
    out = []
    for r in A['file_stops']:
        verdict, note, prop = COORD.get(r['file_id'], ('ok', OK_NOTES.get(r['file_id'], ''), None))
        mem = []
        for rt in sorted(r['only_file_disabled'] + r['only_file_absent'], key=lambda x: (len(x), x)):
            mem.append({'route': rt, 'kind': 'file-only' if rt in r['only_file_absent'] else 'db-disabled',
                        'note': MEMBERSHIP.get((r['file_id'], rt), '')})
        for rt in r['only_db']:
            mem.append({'route': rt, 'kind': 'db-only',
                        'note': 'маршрут 9 з 2025 р., у файлі 2024 його ще немає' if rt == '9' else ''})
        out.append({**{k: r.get(k) for k in ('file_id', 'file_name', 'file_street', 'file_house', 'db_id', 'db_name',
                                             'renamed', 'merged_with', 'lat', 'lon', 'd_file_street', 'd_addr',
                                             'routes_file', 'routes_db_active', 'routes_db_disabled')},
                    'addr_method': (r.get('addr') or {}).get('method'),
                    'nearest_osm_stop': r['nearest_osm_stops'][0][:2] if r.get('nearest_osm_stops') else None,
                    'coord_verdict': verdict, 'coord_note': note,
                    'proposal': {'lat': prop[0], 'lon': prop[1], 'source': prop[2]} if prop else None,
                    'membership': mem})
    save(path('stops-review.json'), {'db_snapshot': A['db_snapshot'], 'file_stops': out,
                                     'db_only_stops': A['db_only_stops']})
    print('stops-review.json:', {v: sum(1 for x in out if x['coord_verdict'] == v) for v in ('ok', 'doubt', 'wrong')})


if __name__ == '__main__':
    main()
