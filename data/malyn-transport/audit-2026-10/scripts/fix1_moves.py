"""Фаза 1 виправлень: перенесення 6 хибних точок + їхнє місце на кожному маршруті.
Рішення — з розбору (Docs/transport-stops-fix-2026-10.md, фаза 1). --dry: лише перевірка; --apply: запис."""
import sys

from apply_lib import apply_change, chain, insert_after, move_stop, recalc, set_chains

MOVES = {  # нова точка (на узбіччі з боку адреси), джерело
    'st_0042': (50.775067, 29.25091),   # «м-н Будматеріали» — Грушевського 77, навпроти магазину (OSM)
    'st_0082': (50.778392, 29.260531),  # «сквер Жертв Чорнобиля» — Грушевського 99, біля «Дзвону Чорнобиля» (OSM)
    'st_0008': (50.770927, 29.281599),  # «Вербицького» — OSM-зупинка «Вул. Крилова» на вул. Вербицького
    'st_0037': (50.7774, 29.21085),     # «Лісна» — OSM-зупинка «Лісна» на заході 10-ї ОГШБ
    'st_0010': (50.76487, 29.292149),   # «ГМП 14» — вул. Героїв Малинського Підпілля, бік буд. 14
    'st_0011': (50.764744, 29.292148),  # «ГМП 14 (навпроти)» — через дорогу
}
T3 = 'st_0113'  # №7 т.3 — північна дорога (OSM 2017), №7 тепер їде вулицею ГМП


def build(d):
    for sid, (la, lo) in MOVES.items():
        move_stop(d, sid, la, lo)
    # №3: «Будматеріали» і «сквер» — лише «назад» (правий бік у бік центру); «Лісна» — між т.2 і т.1
    t3, b3 = chain(d, '3', 'orderThere'), chain(d, '3', 'orderBack')
    t3.remove('st_0037'); t3 = insert_after(t3, 'st_0037', 'st_0110')               # т.2 → Лісна → т.1
    b3.remove('st_0037'); b3 = insert_after(b3, 'st_0037', 'st_0109')               # т.1 → Лісна → т.2
    b3 = insert_after(b3, 'st_0082', 'st_0054')                                      # Малинівський круг → сквер
    b3 = insert_after(b3, 'st_0042', 'st_0013')                                      # Грушевського 87 → Будматеріали
    set_chains(d, '3', t3, b3)
    # №12: так само «Будматеріали» і «сквер» у бік центру
    t12, b12 = chain(d, '12', 'orderThere'), chain(d, '12', 'orderBack')
    b12 = insert_after(b12, 'st_0082', 'st_0054')
    b12 = insert_after(b12, 'st_0042', 'st_0013')
    set_chains(d, '12', t12, b12)
    # №7: «ГМП 14» на вулиці ГМП: туди 14 ОМБ → ГМП 14 → т.4; назад т.4 → ГМП 14 (навпроти) → 14 ОМБ (навпр); т.3 — -1
    t7, b7 = chain(d, '7', 'orderThere'), chain(d, '7', 'orderBack')
    t7 = [x for x in t7 if x not in ('st_0010', T3)]; t7 = insert_after(t7, 'st_0010', 'st_0002')
    b7 = [x for x in b7 if x not in ('st_0011', T3)]; b7 = insert_after(b7, 'st_0011', 'st_0114')
    set_chains(d, '7', t7, b7)
    return d


if __name__ == '__main__':
    dry = '--apply' not in sys.argv
    cur, after = apply_change('fix1', build, MOVES.keys(), {'3', '7', '12'}, dry=dry)
    if not dry:
        recalc('fix1', ['3', '7'])  # у №12 сегментів немає — не створюємо
