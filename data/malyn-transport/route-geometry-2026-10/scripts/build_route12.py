"""Фаза 8: технічні точки для лінії №12 — ті самі правила, що для №8 і №7 (build_more.build_routes).

№12 за нинішнім ланцюжком бази: Поліклініка → 10-ї ОГШБ → Шевченка → центр → Грушевського → Малинівський круг →
Огієнка → вокзал (і назад тими самими вулицями). «Назад» зупинку для маршрутизації проєктуємо на лінію №12 з OSM
(relation 7423159, лише цей напрямок), якщо вона ближче REL_MAX; «туди» — загальне правило. «Малинівський круг» —
на в'їзді на кільце / виїзді з нього (див. anchors). Петля біля вокзалу т.2–т.4 лишається як є (вона вже в ланцюжку).
«Ярослава Мудрого» і «Грушевського 87» стояли за адресою будинку, 25–33 м від дороги, — переносимо до узбіччя.
Заїзд Заводська → Вербицького (офіційний перелік 2024 і OSM) тут не додаємо: ці зупинки в №12 вимкнені, а лінія OSM
неповна (див. Docs/route-geometry-12-2026-10.md).
Час: сегментів у №12 не було (кожен перегін — 120 с за замовчуванням); відрізки між справжніми зупинками
зберігаємо такими самими й ділимо між новими перегонами за довжиною. Нічого не записує, якщо не передати --apply."""
import re
import sys

from build_more import DROP_TECH, build_routes, osm_route_anchors, osm_ways_projection, put_routes  # шляхи
from apply_lib import move_stop  # noqa: E402
from common import xy  # noqa: E402
from geo_lib import axis_point, unxy  # noqa: E402

ROUTES = ['12']
REL = 7423159    # OSM: «Залізничний вокзал - Лікарня ч/з Крилова #12»
REL_MAX = 35.0   # м — далі від лінії OSM зупинку не проєктуємо


MK = 'st_0054'
MK_IN = [487934110, 487526372]   # OSM: в'їзд на кільце з Грушевського із заходу (туди)
MK_OUT = [410084354, 487526369]  # OSM: виїзд з кільця на Грушевського на захід (назад)


def anchors(st):
    """Лінія №12 в OSM описує лише напрямок «назад» (від вокзалу), а біля Малинівського круга Грушевського має дві
    окремі проїжджі частини. Тож лінію OSM беремо лише для «назад»; «туди» — загальне правило. «Малинівський круг»
    — на в'їзді на кільце (туди) і на виїзді з нього (назад): №12 під'їжджає Грушевського із заходу, а не з боку
    Кульчицького, як №5 і №11, для яких загальне правило ставить цю зупинку."""
    out = osm_route_anchors(st, '12', REL, REL_MAX, keys=('orderBack',))
    p = (st[MK]['lat'], st[MK]['lng'])
    out[('12', 'orderThere', MK)] = osm_ways_projection(p, MK_IN)
    out[('12', 'orderBack', MK)] = osm_ways_projection(p, MK_OUT)
    return out


def orphans(d):
    """Технічні точки, що не стоять на жодному маршруті (старі ручні точки зі статтями) — не перевикористовуємо."""
    used = {x['stopId'] for x in d['routeStops']}
    return {s['id'] for s in d['stops'] if re.match(r'^№\S+ т\.\d+$', s['name']) and s['id'] not in used}


CURB = {'st_0100': 7.0, 'st_0013': 7.0}  # «Ярослава Мудрого», «Грушевського 87» — м від осі Грушевського
GRUSH = 'вулиця Михайла Грушевського'


def to_curb(d):
    """Зупинки, поставлені за адресою будинку (25–33 м від дороги), — до узбіччя: та сама точка вздовж вулиці й той
    самий бік, CURB м від осі (зупинки спільні з №3 і прихованим №1)."""
    for s in d['stops']:
        if s['id'] in CURB:
            dist, (cx, cy), _ = axis_point(s['lat'], s['lng'], GRUSH)
            px, py = xy(s['lat'], s['lng'])
            k = CURB[s['id']] / dist
            lat, lng = unxy(cx + (px - cx) * k, cy + (py - cy) * k)
            move_stop(d, s['id'], round(lat, 6), round(lng, 6))
    return d


def build(d):
    return build_routes(to_curb(d), ROUTES, special_fn=anchors,
                        pool_skip=set().union(*DROP_TECH.values()) | orphans(d))


if __name__ == '__main__':
    put_routes(build, ROUTES, 'geom-7', '--apply' not in sys.argv, moved=set(CURB))
