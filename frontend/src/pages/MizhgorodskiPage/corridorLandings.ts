export function getCorridorLanding(slug: string | undefined): CorridorLanding | undefined {
  return CORRIDOR_LANDINGS.find((c) => c.slug === slug);
}

export function corridorPath(slug: CorridorLandingSlug): string {
  return `/mizhgorodski/${slug}`;
}

export function corridorSearchHref(landing: CorridorLanding, date?: string): string {
  const params = new URLSearchParams();
  params.set('from', landing.from);
  params.set('to', landing.to);
  if (date) params.set('date', date);
  return `/mizhgorodski?${params.toString()}`;
}
