import { describe, expect, it } from 'vitest';
import { spokenNumbersToDigits as d } from './spokenNumbers';

describe('spokenNumbersToDigits · година', () => {
  it.each([
    ['З малинської лікарні до Києва завтра о шостій ранку', 'З малинської лікарні до Києва завтра о 6:00 ранку'],
    ['Коли буде на прожекторі маршрутка на вокзал після чотирнадцятої', 'Коли буде на прожекторі маршрутка на вокзал після 14:00'],
    ['Як доїхати з паперової фабрики о сімнадцятій', 'Як доїхати з паперової фабрики о 17:00'],
    ["Щоб бути в міській лікарні до дев'ятої з Черемушок", 'Щоб бути в міській лікарні до 9:00 з Черемушок'],
    ['Мені з Пашин на залізничний вокзал о восьмій ранку', 'Мені з Пашин на залізничний вокзал о 8:00 ранку'],
    ['о двадцять першій', 'о 21:00'],
    ['о пів на восьму', 'о 7:30'],
    ['пів на першу', '0:30'],
  ])('%s', (input, expected) => {
    expect(d(input)).toBe(expected);
  });

  it('«до другої лікарні» — не година', () => {
    expect(d('до другої лікарні')).toBe('до другої лікарні');
  });
});

describe('spokenNumbersToDigits · числа й номери', () => {
  it.each([
    ['З Малина до Києва на Хрещатик двадцять два', 'З Малина до Києва на Хрещатик 22'],
    ['Як доїхати з вулиці Будівельників, сім, до центру крім одинадцятого', 'Як доїхати з вулиці Будівельників, 7, до центру крім 11'],
    ["Коновальця сорок п'ять до паперової фабрики", 'Коновальця 45 до паперової фабрики'],
    ['Київ, Предславинська двадцять вісім, до Севастопольської площі', 'Київ, Предславинська 28, до Севастопольської площі'],
    ['від Святошина до Володимирської двадцять вісім а Малин', 'від Святошина до Володимирської 28а Малин'],
    ['Київ, Ентузіастів сім дріб один, до Святошина', 'Київ, Ентузіастів 7/1, до Святошина'],
    ['Від лікарні до вокзалу крім другого маршруту в неділю', 'Від лікарні до вокзалу крім 2 маршруту в неділю'],
  ])('%s', (input, expected) => {
    expect(d(input)).toBe(expected);
  });

  it('текст без чисел словами не змінюється', () => {
    expect(d('З Пашин до вокзалу')).toBe('З Пашин до вокзалу');
    expect(d('Коли їдуть п’ятірка і сімка з лікарні')).toBe('Коли їдуть п’ятірка і сімка з лікарні');
  });
});
