/**
 * «Доведе» · голос: що робимо з розпізнаним текстом, перш ніж віддати його полю питання (Docs/dovede-voice-roadmap.md,
 * Ф1·2): числа словами → цифри і кілька відомих «помилок слуху» Web Speech. Правила взято з живого прогону лабораторії
 * (`Docs/dovede/research/voice-lab-2026-11-22.json`) і з журналу питань; нове слово, яке слух псує, спершу вчимо в
 * адмінці («Словник» → синоніми), а сюди — лише те, що синонімом не виправити (склеєні прийменники, «Крим» → «крім»).
 */
import { spokenNumbersToDigits } from './spokenNumbers';

/** Слово закінчується тут: пробіл, кінець рядка чи розділовий знак */
const END = '(?=\\s|$|[.,!?])';

const RULES: ReadonlyArray<readonly [RegExp, string]> = [
  // «змалена на Київ» → «з Малина на Київ» (прийменник склеївся зі словом)
  [new RegExp(`(^|\\s)з(?:і)?мал(?:ена|ина|ине|ини)${END}`, 'giu'), '$1з Малина'],
  // «де мало на» → «до Малина»
  [new RegExp(`(^|\\s)де\\s+мало\\s+на${END}`, 'giu'), '$1до Малина'],
  // «зпашина» → «з Пашин»
  [new RegExp(`(^|\\s)зпашин(?:а|и)?${END}`, 'giu'), '$1з Пашин'],
  // «Крим другого маршруту», «Крим 2» → «крім …»: після нього йде номер маршруту
  [/(^|\s)крим(?=\s+(?:\d|\p{L}+\s+маршрут))/giu, '$1крім'],
];

export function fixHeard(text: string): string {
  return RULES.reduce((t, [re, to]) => t.replace(re, to), text);
}

/** Усе, що з розпізнаного тексту робить питання для поля: числа словами → цифри, потім відомі помилки слуху */
export function prepareHeard(text: string): string {
  return fixHeard(spokenNumbersToDigits(text)).replace(/\s+/g, ' ').trim();
}
