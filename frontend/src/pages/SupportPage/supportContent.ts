export function supportTopicPath(id: SupportTopicId): string {
  return `${SUPPORT_PATH}/${id}`;
}

export function isSupportTopicId(value: string | undefined): value is SupportTopicId {
  return SUPPORT_TOPICS.some((t) => t.id === value);
}

